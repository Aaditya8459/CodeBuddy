/*
|--------------------------------------------------------------------------
| Execution Profile
|--------------------------------------------------------------------------
*/

export interface ExecutionProfile
    extends ResourceLimits {
    language: string;

    mode: ExecutionMode;
}

/*
|--------------------------------------------------------------------------
| Merge Limits
|--------------------------------------------------------------------------
*/

export function getExecutionLimits(
    language: string,
    overrides: Partial<ResourceLimits> = {}
): ResourceLimits {
    const normalizedLanguage =
        language
            .trim()
            .toLowerCase();

    const languageLimits =
        LANGUAGE_EXECUTION_LIMITS[
            normalizedLanguage
        ] ?? {};

    return {
        ...DEFAULT_EXECUTION_LIMITS,

        ...languageLimits,

        ...overrides,
    };
}

/*
|--------------------------------------------------------------------------
| Get Execution Profile
|--------------------------------------------------------------------------
*/

export function getExecutionProfile(
    language: string,
    mode: ExecutionMode = "run",
    overrides: Partial<ResourceLimits> = {}
): ExecutionProfile {
    return {
        language:
            language
                .trim()
                .toLowerCase(),

        mode,

        ...getExecutionLimits(
            language,
            overrides
        ),
    };
}

/*
|--------------------------------------------------------------------------
| Compilation Limits
|--------------------------------------------------------------------------
|
| Compilation should normally receive more time than execution.
|
|--------------------------------------------------------------------------
*/

export function getCompilationLimits(
    language: string
): ResourceLimits {
    const base =
        getExecutionLimits(
            language
        );

    return {
        ...base,

        timeoutMs:
            Math.max(
                base.timeoutMs,
                30_000
            ),

        maxOutputBytes:
            Math.max(
                base.maxOutputBytes,
                4 * 1024 * 1024
            ),
    };
}

