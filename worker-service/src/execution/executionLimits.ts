/*
|--------------------------------------------------------------------------
| CodeBuddy Execution Limits
|--------------------------------------------------------------------------
|
| Centralized execution limits for code running inside room containers.
|
| These limits are applied by the execution layer before/during execution.
|
| Architecture:
|
|   Room
|     │
|     ▼
|   Docker Container
|     │
|     ▼
|   Execution Manager
|     │
|     ├── Runtime Resolver
|     ├── Execution Limits  <── THIS FILE
|     └── Process Runner
|
|--------------------------------------------------------------------------
*/

/*
|--------------------------------------------------------------------------
| Supported Execution Modes
|--------------------------------------------------------------------------
*/

export type ExecutionMode =
    | "run"
    | "compile"
    | "test"
    | "build"
    | "terminal";

/*
|--------------------------------------------------------------------------
| Resource Limits
|--------------------------------------------------------------------------
*/

export interface ResourceLimits {
    /*
     * Maximum execution time for a single process.
     *
     * Example:
     * Python program gets 10 seconds.
     */
    timeoutMs: number;

    /*
     * Maximum amount of memory available to the process.
     */
    memoryBytes: number;

    /*
     * Maximum memory including swap.
     *
     * Use 0 when swap should not be allowed.
     */
    memorySwapBytes: number;

    /*
     * Maximum number of processes/threads.
     */
    pidsLimit: number;

    /*
     * Maximum CPU allocation.
     *
     * Docker NanoCPUs:
     *
     * 1 CPU = 1_000_000_000
     */
    nanoCpus: number;

    /*
     * Maximum output generated by stdout.
     */
    maxStdoutBytes: number;

    /*
     * Maximum output generated by stderr.
     */
    maxStderrBytes: number;

    /*
     * Maximum combined stdout + stderr.
     */
    maxOutputBytes: number;

    /*
     * Maximum source code size.
     */
    maxSourceBytes: number;

    /*
     * Maximum number of files involved in execution.
     */
    maxFiles: number;

    /*
     * Maximum file size that execution may generate.
     */
    maxGeneratedFileBytes: number;

    /*
     * Maximum total workspace growth caused by execution.
     */
    maxWorkspaceGrowthBytes: number;
}

