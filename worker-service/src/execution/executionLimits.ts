/*
|--------------------------------------------------------------------------
| Validation Errors
|--------------------------------------------------------------------------
*/

export class ExecutionLimitError
    extends Error {
    constructor(
        message: string
    ) {
        super(message);

        this.name =
            "ExecutionLimitError";
    }
}

/*
|--------------------------------------------------------------------------
| Validate Source Size
|--------------------------------------------------------------------------
*/

export function validateSourceSize(
    sizeBytes: number,
    limits: ResourceLimits
): void {
    if (
        !Number.isFinite(
            sizeBytes
        ) ||
        sizeBytes < 0
    ) {
        throw new ExecutionLimitError(
            "Invalid source size"
        );
    }

    if (
        sizeBytes >
        limits.maxSourceBytes
    ) {
        throw new ExecutionLimitError(
            `Source code exceeds maximum allowed size of ${formatBytes(
                limits.maxSourceBytes
            )}`
        );
    }
}

/*
|--------------------------------------------------------------------------
| Validate File Count
|--------------------------------------------------------------------------
*/

export function validateFileCount(
    fileCount: number,
    limits: ResourceLimits
): void {
    if (
        !Number.isInteger(
            fileCount
        ) ||
        fileCount < 0
    ) {
        throw new ExecutionLimitError(
            "Invalid file count"
        );
    }

    if (
        fileCount >
        limits.maxFiles
    ) {
        throw new ExecutionLimitError(
            `Execution contains too many files. Maximum allowed: ${limits.maxFiles}`
        );
    }
}

