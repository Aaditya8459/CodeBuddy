/*
|--------------------------------------------------------------------------
| Calculate CPU Cores
|--------------------------------------------------------------------------
*/

export function nanoCpusToCores(
    nanoCpus: number
): number {
    return (
        nanoCpus /
        1_000_000_000
    );
}

/*
|--------------------------------------------------------------------------
| Calculate Bytes
|--------------------------------------------------------------------------
*/

export function formatBytes(
    bytes: number
): string {
    if (
        bytes === 0
    ) {
        return "0 B";
    }

    const units = [
        "B",
        "KB",
        "MB",
        "GB",
        "TB",
    ];

    const index =
        Math.floor(
            Math.log(bytes) /
                Math.log(1024)
        );

    const safeIndex =
        Math.min(
            index,
            units.length - 1
        );

    const value =
        bytes /
        Math.pow(
            1024,
            safeIndex
        );

    return `${value.toFixed(
        value >= 10 ? 0 : 2
    )} ${units[safeIndex]}`;
}

/*
|--------------------------------------------------------------------------
| Environment Overrides
|--------------------------------------------------------------------------
|
| Production deployments can change the global limits without
| modifying source code.
|
| Example .env:
|
| EXECUTION_TIMEOUT_MS=10000
| EXECUTION_MEMORY_MB=512
| EXECUTION_PIDS_LIMIT=64
|
|--------------------------------------------------------------------------
*/

function getEnvNumber(
    name: string,
    fallback: number
): number {
    const value =
        process.env[name];

    if (
        value === undefined ||
        value.trim() === ""
    ) {
        return fallback;
    }

    const parsed =
        Number(value);

    if (
        !Number.isFinite(
            parsed
        ) ||
        parsed <= 0
    ) {
        return fallback;
    }

    return parsed;
}

