/*
|--------------------------------------------------------------------------
| Validate Resource Limits
|--------------------------------------------------------------------------
*/

export function validateLimits(
    limits: ResourceLimits
): void {
    if (
        limits.timeoutMs <= 0
    ) {
        throw new ExecutionLimitError(
            "timeoutMs must be greater than zero"
        );
    }

    if (
        limits.memoryBytes <= 0
    ) {
        throw new ExecutionLimitError(
            "memoryBytes must be greater than zero"
        );
    }

    if (
        limits.memorySwapBytes <
        limits.memoryBytes
    ) {
        throw new ExecutionLimitError(
            "memorySwapBytes cannot be lower than memoryBytes"
        );
    }

    if (
        limits.pidsLimit <= 0
    ) {
        throw new ExecutionLimitError(
            "pidsLimit must be greater than zero"
        );
    }

    if (
        limits.nanoCpus <= 0
    ) {
        throw new ExecutionLimitError(
            "nanoCpus must be greater than zero"
        );
    }

    if (
        limits.maxStdoutBytes <= 0
    ) {
        throw new ExecutionLimitError(
            "maxStdoutBytes must be greater than zero"
        );
    }

    if (
        limits.maxStderrBytes <= 0
    ) {
        throw new ExecutionLimitError(
            "maxStderrBytes must be greater than zero"
        );
    }

    if (
        limits.maxOutputBytes <= 0
    ) {
        throw new ExecutionLimitError(
            "maxOutputBytes must be greater than zero"
        );
    }

    if (
        limits.maxSourceBytes <= 0
    ) {
        throw new ExecutionLimitError(
            "maxSourceBytes must be greater than zero"
        );
    }

    if (
        limits.maxFiles <= 0
    ) {
        throw new ExecutionLimitError(
            "maxFiles must be greater than zero"
        );
    }

    if (
        limits.maxGeneratedFileBytes <=
        0
    ) {
        throw new ExecutionLimitError(
            "maxGeneratedFileBytes must be greater than zero"
        );
    }

    if (
        limits.maxWorkspaceGrowthBytes <=
        0
    ) {
        throw new ExecutionLimitError(
            "maxWorkspaceGrowthBytes must be greater than zero"
        );
    }
}

/*
|--------------------------------------------------------------------------
| Clamp Requested Limits
|--------------------------------------------------------------------------
|
| User/client input should NEVER be allowed to increase the
| server-defined maximum.
|
|--------------------------------------------------------------------------
*/

