/*
|--------------------------------------------------------------------------
| Validate Timeout
|--------------------------------------------------------------------------
*/

export function validateTimeout(
    timeoutMs: number,
    limits: ResourceLimits
): void {
    if (
        !Number.isFinite(
            timeoutMs
        ) ||
        timeoutMs <= 0
    ) {
        throw new ExecutionLimitError(
            "Invalid execution timeout"
        );
    }

    if (
        timeoutMs >
        limits.timeoutMs
    ) {
        throw new ExecutionLimitError(
            `Requested timeout exceeds maximum allowed timeout of ${limits.timeoutMs}ms`
        );
    }
}

